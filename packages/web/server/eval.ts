/**
 * npm run plan:eval — run the AI planner on five unrelated questions against the real GroqCloud API,
 * validate each proposal, convert it (as if accepted with everything selected) into a reality with the
 * existing operations, and write docs/validation/ai-planner-eval.{json,md}. Needs GROQ_API_KEY.
 * Calls are spaced 12 s apart (the planner's own limit is 1 per 10 s). Nothing is retried on 429.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadEnv } from "vite";
import { evaluateBranch, proposalToReality, selectAll, exportRealities, importRealities } from "@realityfork/core";
import { createPlanner, type PlanResult } from "./planner";

const repoRoot = fileURLToPath(new URL("../../..", import.meta.url));
const webRoot = fileURLToPath(new URL("..", import.meta.url));
const env = { ...loadEnv("development", repoRoot, "GROQ_"), ...loadEnv("development", webRoot, "GROQ_") };
const apiKey = process.env.GROQ_API_KEY || env.GROQ_API_KEY;
const model = process.env.GROQ_MODEL || env.GROQ_MODEL || "openai/gpt-oss-120b";

const CASES = [
  "What if I opened a restaurant?",
  "What if I moved to another country?",
  "What if my university changed examination scheduling?",
  "What if my household installed solar panels?",
  "What if I chose a different career?",
];

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
const planner = createPlanner({ apiKey, model, minIntervalMs: 10_000 });
const results: { question: string; result: PlanResult; conversion: unknown }[] = [];
for (const [i, q] of CASES.entries()) {
  if (i > 0) await sleep(12_000);
  const result = await planner.plan(q);
  let conversion: unknown = null;
  if (result.ok) {
    try {
      const r = await proposalToReality(q, result.proposal, selectAll(result.proposal), { model: result.model, createdAt: new Date().toISOString() });
      const [back] = await importRealities(exportRealities([r]));
      const outs = r.branches.map((b) => ({ branch: b.name, ...evaluateBranch(r, b) }));
      conversion = {
        ok: true, branches: r.branches.map((b) => b.name), variables: r.variables.length, formulas: r.formulas.length,
        possibilities: r.branches.reduce((s, b) => s + b.possibilities.length, 0), exportRoundTrip: JSON.stringify(back) === JSON.stringify(r),
        calculatedStatuses: outs.map((o) => ({ branch: o.branch, statuses: o.calculated.map((c) => c.result.status) })),
        allNumbersUnknown: r.variables.filter((v) => v.kind === "number").every((v) => r.branches.every((b) => b.values[v.key] === null)),
      };
    } catch (e) {
      conversion = { ok: false, error: (e as Error).message };
    }
  }
  results.push({ question: q, result, conversion });
  console.log(`${q} → ${result.ok ? `ok (attempts ${result.attempts}, ${result.ms} ms)` : `${result.code}: ${result.message}`}`);
}

const out = fileURLToPath(new URL("../../../docs/validation/ai-planner-eval", import.meta.url));
writeFileSync(`${out}.json`, JSON.stringify({ recordedAt: new Date().toISOString(), model, keyPresent: Boolean(apiKey), results }, null, 2));
const md: string[] = [`# AI planner evaluation (generated by npm run plan:eval)`, "", `Recorded ${new Date().toISOString()}, model \`${model}\`. Raw data: ai-planner-eval.json.`, ""];
for (const { question, result, conversion } of results) {
  md.push(`## ${question}`, "");
  if (!result.ok) {
    md.push(`**Failed:** ${result.code} (HTTP ${result.status}). ${result.message}`, ...(result.errors ?? []).map((e) => `- ${e}`), "");
    continue;
  }
  const p = result.proposal;
  md.push(`Attempts: ${result.attempts}. Time: ${result.ms} ms. Usage: \`${JSON.stringify(result.usage)}\``, "", `**Interpretation:** ${p.interpretation}`, "");
  md.push("**Branches:**", ...p.branches.map((b) => `- ${b.name}: ${b.description}${b.settings.length ? ` (${b.settings.map((s) => `${s.variable} = ${s.value}`).join(", ")})` : ""}`), "");
  md.push("**Assumptions:**", ...p.variables.map((v) => `- \`${v.key}\` ${v.label} (${v.kind}${v.unit ? `, ${v.unit}` : ""}${v.options.length ? `: ${v.options.join(" / ")}` : ""}): ${v.why}`), "");
  md.push("**Questions:**", ...p.questions.map((q) => `- ${q}`), "");
  md.push("**Formulas:**", ...(p.formulas.length ? p.formulas.map((f) => `- ${f.label} = \`${f.expression}\`${f.condition ? ` when \`${f.condition}\`` : ""}${f.unit ? ` [${f.unit}]` : ""}: ${f.explanation}`) : ["- none"]), "");
  md.push("**Speculative possibilities:**", ...p.possibilities.map((x) => `- (${x.branch}, ${x.tone}) ${x.text}`), "");
  md.push("**Missing evidence:**", ...p.missingEvidence.map((x) => `- ${x}`), "", "**Limitations:**", ...p.limitations.map((x) => `- ${x}`), "");
  md.push(`**Conversion into a reality:** \`${JSON.stringify(conversion)}\``, "");
}
writeFileSync(`${out}.md`, md.join("\n") + "\n");
