/**
 * npm run generate:synthetic
 * Writes SYNTHETIC demo logs and their dataset cards to data/synthetic/. Deterministic: re-running
 * reproduces identical files (the sha256 values in the cards will match).
 *
 *  1. clinic-arrivals-SYNTHETIC.csv  (Tasks 6–8 fixture: λ = 1.5/h, mean service 50 min). Unchanged.
 *  2. frontdesk-arrivals-SYNTHETIC.csv (revision sprint: λ = 16/h, mean service 6 min, constant rate).
 *  3. frontdesk-daily-SYNTHETIC.csv   (revision sprint: time-of-day pattern, see the daypart spike).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { generateDailyPatternLog, generateSyntheticArrivalLog, sha256Hex, type DatasetCard } from "@realityfork/core";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const dir = resolve(root, "data/synthetic");
mkdirSync(dir, { recursive: true });

async function writeCard(fileName: string, csv: string, card: Omit<DatasetCard, "fileName" | "sha256" | "synthetic" | "license">) {
  const { name, ...rest } = card;
  // Field order matches the original Task 6 card so regeneration is byte-identical.
  const full: DatasetCard = { name, fileName, sha256: await sha256Hex(csv), synthetic: true, license: "CC0-1.0", ...rest };
  writeFileSync(resolve(dir, fileName), csv);
  writeFileSync(resolve(dir, fileName.replace(/\.csv$/, ".card.json")), JSON.stringify(full, null, 2) + "\n");
  console.log(`wrote data/synthetic/${fileName} (sha256 ${full.sha256})`);
}

// 1. Original clinic fixture (kept byte-identical for earlier evidence).
{
  const params = { seed: 424242, arrivalRatePerHour: 1.5, meanServiceMinutes: 50, start: "2026-03-02T00:00:00Z", hours: 400 };
  const log = generateSyntheticArrivalLog(params);
  await writeCard("clinic-arrivals-SYNTHETIC.csv", log.csv, {
    name: "Clinic front desk arrivals (SYNTHETIC)",
    description:
      "SYNTHETIC data. Not observations of any real clinic. Generated by RealityFork from a stationary Poisson arrival process and exponential service times with the known parameters below, so that parameter recovery can be checked.",
    generator: "packages/core/src/data/synthetic.ts generateSyntheticArrivalLog (RNG xoshiro128**)",
    generatorParameters: { ...params, serviceRatePerHour: 60 / params.meanServiceMinutes },
    observationWindow: { start: log.windowStart, end: log.windowEnd },
    columns: { arrival_time: "ISO 8601 arrival instant, UTC (Z)", service_minutes: "service duration in minutes, 2 decimals" },
    serviceDurationUnit: "minutes",
  });
}

// 2. Front-desk example: 16 arrivals/h, 10 services per staff member per hour (6 min), 2 staff = 80% busy.
{
  const params = { seed: 16106, arrivalRatePerHour: 16, meanServiceMinutes: 6, start: "2026-03-02T00:00:00Z", hours: 40 };
  const log = generateSyntheticArrivalLog(params);
  await writeCard("frontdesk-arrivals-SYNTHETIC.csv", log.csv, {
    name: "Front desk arrivals, constant rate (SYNTHETIC)",
    description: "SYNTHETIC data. Not observations of any real service location. 40 hours of continuous operation with a constant arrival rate of 16/h and exponential service times with mean 6 minutes (10 per staff member per hour).",
    generator: "packages/core/src/data/synthetic.ts generateSyntheticArrivalLog (RNG xoshiro128**)",
    generatorParameters: { ...params, serviceRatePerHour: 60 / params.meanServiceMinutes },
    observationWindow: { start: log.windowStart, end: log.windowEnd },
    columns: { arrival_time: "ISO 8601 arrival instant, UTC (Z)", service_minutes: "service duration in minutes, 2 decimals" },
    serviceDurationUnit: "minutes",
  });
}

// 3. Daily pattern for the daypart spike: open 08:00–20:00 local time (UTC−05:00 fixed), 10 days.
{
  const rates = [8, 14, 24, 14, 10, 6];
  const params = { seed: 777, days: 10, firstDay: "2026-03-02", utcOffsetMinutes: -300, openHour: 8, blockHours: 2, meanServiceMinutes: 6 };
  const log = generateDailyPatternLog({ ...params, ratesPerHour: rates });
  await writeCard("frontdesk-daily-SYNTHETIC.csv", log.csv, {
    name: "Front desk arrivals with a lunchtime peak (SYNTHETIC)",
    description:
      "SYNTHETIC data. Not observations of any real service location. 10 days, open 08:00–20:00 local time at a fixed UTC−05:00 offset (no daylight-saving changes). Arrival rate is piecewise constant over six 2-hour blocks; exponential service times with mean 6 minutes.",
    generator: "packages/core/src/data/synthetic.ts generateDailyPatternLog (piecewise-constant Poisson by time change)",
    generatorParameters: { ...params, ratesPerHour: rates.join(",") },
    observationWindow: { start: log.windowStart, end: log.windowEnd },
    columns: { arrival_time: "ISO 8601 arrival instant with -05:00 offset", service_minutes: "service duration in minutes, 2 decimals" },
    serviceDurationUnit: "minutes",
  });
}
